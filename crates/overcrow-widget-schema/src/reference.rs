/// Member tables of a record shape, nested records and alternatives
/// flattened with a dotted prefix.
fn shape_members(out: &mut String, shape: &Shape, prefix: &str) {
    match shape {
        Shape::Record(members) => {
            if prefix.is_empty() {
                out.push_str("| Member | Shape | Meaning |\n| --- | --- | --- |\n");
            }
            for member in *members {
                let name = format!("{prefix}{}", member.name);
                let _ = writeln!(
                    out,
                    "| `{name}` | {} | {} |",
                    member.shape.describe(),
                    member.summary
                );
                let inner = match member.shape {
                    Shape::Nullable(inner) => *inner,
                    other => other,
                };
                if let Shape::Record(_) = inner {
                    shape_members(out, &inner, &format!("{name}."));
                }
            }
            if prefix.is_empty() {
                out.push('\n');
            }
        }
        Shape::OneOf(shapes) => {
            for shape in *shapes {
                shape_members(out, shape, prefix);
            }
        }
        _ => {}
    }
}

fn services_section(out: &mut String) {
    out.push_str(
        "\n## Services\n\nAuthority is checked by the host at every call, immediately before \
acting. Gesture services also require the `cause` of a gesture event of the current Interactive \
epoch.\n\n| Service | Requires | Kind | Gesture | Confirmation | Parameters | Result | Shape | Status |\n\
| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for service in SERVICES {
        let requires = match service.requires {
            Requirement::None => "nothing".to_string(),
            Requirement::Permission(name) => format!("permission `{name}`"),
            Requirement::Capability(name) => format!("capability `{name}`"),
        };
        let kind = match service.kind {
            ServiceKind::Call => "call",
            ServiceKind::Subscribe => "subscribe",
        };
        let params = if service.params.is_empty() {
            "none".to_string()
        } else {
            service
                .params
                .iter()
                .map(|field| {
                    let optional = if field.required { "" } else { "?" };
                    format!("`{}{optional}`: {}", field.name, field.ty.describe())
                })
                .collect::<Vec<_>>()
                .join("; ")
        };
        let _ = writeln!(
            out,
            "| `{}` | {requires} | {kind} | {} | {} | {params} | {} | {} | {} |",
            service.name,
            yes(service.gesture),
            yes(service.confirm),
            service.result,
            service.returns.describe(),
            status(service.status)
        );
    }
    out.push_str(
        "\n### Result shapes\n\nThe shape of each result and subscription update, and of \
`ServiceError`. Records are exact: every member is present, a nullable one as `null`, and no \
other key is. Integers stay below 2^53.\n\n",
    );
    for named in SHAPES {
        let _ = write!(
            out,
            "#### `{}`\n\n{} {}\n\n",
            named.name,
            named.summary,
            named.shape.describe()
        );
        shape_members(out, &named.shape, "");
    }
    let _ = write!(
        out,
        "\nService error codes: {}.\n\n### Write intents\n\n\
A `form` with an `intent` sends the values of its named host-owned controls straight to the \
service when the user submits it; the VM receives a `submit` event with the outcome but never \
supplies the body. Named controls not listed are rejected.\n\n",
        code_list(SERVICE_ERRORS)
    );
    for intent in WRITE_INTENTS {
        let target = match intent.target {
            Target::Refused => "refused".to_string(),
            Target::Optional(meaning) => format!("optional ({meaning})"),
            Target::Required(meaning) => format!("required ({meaning})"),
        };
        let _ = write!(
            out,
            "#### `{}`\n\nCapability `{}`; `target` attribute {target}. Status: {}.\n\n",
            intent.name,
            intent.capability,
            status(intent.status)
        );
        fields_table(out, intent.fields);
    }
}

