pub const DOCUMENT_PATH: &str = "docs/widget-schema-v1.md";

pub fn markdown() -> String {
    let mut out = String::new();
    intro(&mut out);
    limits_section(&mut out);
    view_section(&mut out);
    style_section(&mut out);
    tokens_section(&mut out);
    icons_section(&mut out);
    manifest_section(&mut out);
    wrapper_section(&mut out);
    permissions_section(&mut out);
    services_section(&mut out);
    ipc_section(&mut out);
    package_section(&mut out);
    catalog_section(&mut out);
    // Sections append blank lines independently; keep at most one between blocks.
    while out.contains("\n\n\n") {
        out = out.replace("\n\n\n", "\n\n");
    }
    out
}

fn intro(out: &mut String) {
    let _ = write!(
        out,
        "# Widget schema v1 reference\n\n\
<!-- Generated by `cargo run -p overcrow-widget-schema --example reference`. Do not edit. -->\n\n\
This reference is generated from the `overcrow-widget-schema` crate, the single source of \
truth of widget API version {API_VERSION} (OverCrow design record ADR 0001, D8). The host, \
the creator CLI and the Studio compile the same tables; anything absent from them is \
rejected.\n\n\
**Status.** A *fixed* value is final for v1; the VM budgets come from the P0.3 measurements \
(ADR 0002), the parity bounds from the P0.4 text spike (ADR 0003), and the sandbox and IPC \
bounds from the P1.6 and P1.7 measurements. A *provisional* value is a conservative placeholder \
until the named lot delivers its evidence: the P2.4 pilots check the light colours; P1.3 and \
P1.8 exercise rendering and service bounds. Capabilities, services and \
write intents follow the P0.6 audit of the built-ins. A \
provisional value is enforced exactly like a fixed one until it is revised.\n\n\
Lengths are logical pixels at 100 % content scale. Text limits count UTF-8 bytes unless the unit \
says characters, which are Unicode scalar values.\n"
    );
}

fn status(status: Status) -> String {
    match status {
        Status::Fixed => "fixed".into(),
        Status::Provisional { lot } => format!("**provisional ({lot})**"),
    }
}

fn amount(limit: &Limit) -> String {
    const KIB: u64 = 1024;
    const MIB: u64 = 1024 * 1024;
    match limit.unit {
        Unit::Bytes if limit.value >= MIB && limit.value.is_multiple_of(MIB) => {
            format!("{} MiB", limit.value / MIB)
        }
        Unit::Bytes if limit.value >= KIB && limit.value.is_multiple_of(KIB) => {
            format!("{} KiB", limit.value / KIB)
        }
        Unit::Count => limit.value.to_string(),
        unit => format!("{} {}", limit.value, unit.as_str()),
    }
}

fn yes(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

fn fields_table(out: &mut String, fields: &[Field]) {
    if fields.is_empty() {
        out.push_str("No fields.\n\n");
        return;
    }
    out.push_str("| Field | Type | Required | Meaning |\n| --- | --- | --- | --- |\n");
    for field in fields {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            field.name,
            field.ty.describe(),
            yes(field.required),
            field.summary
        );
    }
    out.push('\n');
}

fn syntax_table(out: &mut String, heading: &str, entries: &[SyntaxEntry]) {
    let _ = write!(out, "| {heading} | Meaning |\n| --- | --- |\n");
    for entry in entries {
        let _ = writeln!(out, "| `{}` | {} |", entry.syntax, entry.summary);
    }
    out.push('\n');
}

