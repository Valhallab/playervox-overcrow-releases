/// The limits a widget works against; the host enforces them all, and the
/// schema reference lists the others.
fn limits() -> String {
    let mut out = String::from(HEADER);
    for limit in limits::ALL
        .iter()
        .filter(|limit| AUTHOR_LIMITS.contains(&limit.key))
    {
        out.push('\n');
        doc(
            &mut out,
            "",
            &format!("{} ({})", limit.summary, limit.unit.as_str()),
        );
        let _ = writeln!(out, "export const {} = {};", limit.key, limit.value);
    }
    out
}

fn services() -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "\nimport { group } from \"../services.js\";\n\
import type { Listener, Subscription } from \"../services.js\";\n\
import type { ServiceParamsMap as P, ServiceResultMap as R } from \"./schema.js\";\n",
    );
    let mut groups: BTreeMap<&str, Vec<&Service>> = BTreeMap::new();
    for service in SERVICES {
        let (prefix, _) = service.name.split_once('.').unwrap_or((service.name, ""));
        if !HAND_WRITTEN.contains(&prefix) {
            groups.entry(prefix).or_default().push(service);
        }
    }
    for (prefix, services) in &groups {
        let interface = format!("{}Services", pascal(prefix));
        let _ = write!(
            out,
            "\n/** The `{prefix}.*` services. */\nexport interface {interface} "
        );
        let mut tree = Tree::default();
        for service in services {
            let path = &service.name[prefix.len() + 1..];
            tree.insert(path, service);
        }
        tree.write(&mut out, prefix, "");
        out.push('\n');
        let paths: Vec<String> = services
            .iter()
            .map(|service| quote(&service.name[prefix.len() + 1..]))
            .collect();
        let _ = writeln!(
            out,
            "\n/** The `{prefix}.*` services. */\nexport const {}: {interface} = /* @__PURE__ */ group({}, [{}]);",
            prefix,
            quote(prefix),
            paths.join(", ")
        );
    }
    out
}

/// Nested method names of one namespace (`score.subscribe` →
/// `{ score: { subscribe() } }`).
#[derive(Default)]
struct Tree<'a> {
    methods: Vec<(&'a str, &'static Service)>,
    children: BTreeMap<&'a str, Tree<'a>>,
}

impl<'a> Tree<'a> {
    fn insert(&mut self, path: &'a str, service: &'static Service) {
        match path.split_once('.') {
            Some((head, rest)) => self.children.entry(head).or_default().insert(rest, service),
            None => self.methods.push((path, service)),
        }
    }

    fn write(&self, out: &mut String, prefix: &str, indent: &str) {
        let inner = format!("{indent}  ");
        out.push_str("{\n");
        for (name, child) in &self.children {
            let path = format!("{prefix}.{name}");
            doc(out, &inner, &format!("The `{path}.*` services."));
            let _ = write!(out, "{inner}readonly {name}: ");
            child.write(out, &path, &inner);
            out.push_str(";\n");
        }
        for (name, service) in &self.methods {
            method(out, &inner, name, service);
        }
        let _ = write!(out, "{indent}}}");
    }
}

fn method(out: &mut String, indent: &str, name: &str, service: &Service) {
    let mut text = format!("`{}`.", service.name);
    match service.requires {
        Requirement::None => {}
        Requirement::Permission(permission) => {
            let _ = write!(text, " Requires the `{permission}` permission.");
        }
        Requirement::Capability(capability) => {
            let _ = write!(
                text,
                " Requires the `{capability}` capability, granted by the user."
            );
        }
    }
    if service.gesture {
        text.push_str(" Call it while handling a gesture event (`activate`, `keydown`…), or it fails with `gesture_required`.");
    }
    if service.confirm {
        text.push_str(" The host asks the user to confirm first.");
    }
    let _ = write!(
        text,
        " {}: {}.",
        if service.kind == ServiceKind::Subscribe {
            "Updates"
        } else {
            "Result"
        },
        service.result
    );
    doc(out, indent, &text);
    let key = quote(service.name);
    let optional = service.params.iter().all(|field| !field.required);
    let _ = match (service.kind, service.params.is_empty()) {
        (ServiceKind::Subscribe, true) => writeln!(
            out,
            "{indent}{name}(listener: Listener<R[{key}]>): Subscription;"
        ),
        (ServiceKind::Subscribe, false) => writeln!(
            out,
            "{indent}{name}(params: P[{key}], listener: Listener<R[{key}]>): Subscription;"
        ),
        (ServiceKind::Call, true) => writeln!(out, "{indent}{name}(): Promise<R[{key}]>;"),
        (ServiceKind::Call, false) => writeln!(
            out,
            "{indent}{name}(params{}: P[{key}]): Promise<R[{key}]>;",
            if optional { "?" } else { "" }
        ),
    };
}

fn message(name: &str) -> &'static [Field] {
    HOST_MESSAGES
        .iter()
        .find(|message| message.name == name)
        .map_or(&[], |message| message.fields)
}

fn field(fields: &'static [Field], name: &str) -> &'static [&'static str] {
    fields
        .iter()
        .find(|field| field.name == name)
        .map_or(&[], |field| field.keywords())
}

/// An object type literal of `fields`, one member per line.
fn record(out: &mut String, indent: &str, fields: &[Field]) {
    if fields.is_empty() {
        out.push_str("Record<string, never>");
        return;
    }
    let inner = format!("{indent}  ");
    out.push_str("{\n");
    for field in fields {
        doc(out, &inner, field.summary);
        let _ = writeln!(
            out,
            "{inner}readonly {}{}: {};",
            field.name,
            if field.required { "" } else { "?" },
            value_type(&field.ty)
        );
    }
    let _ = write!(out, "{indent}}}");
}

fn value_type(ty: &ValueType) -> String {
    match ty {
        ValueType::Bool => "boolean".into(),
        ValueType::Text(_)
        | ValueType::Chars(_)
        | ValueType::Identifier(_)
        | ValueType::ClassList
        | ValueType::Ref
        | ValueType::RefName => "string".into(),
        ValueType::Integer { .. }
        | ValueType::Number { .. }
        | ValueType::Id
        | ValueType::NodeRef => "number".into(),
        ValueType::Keyword(words) => keywords(words),
        ValueType::Icon => "IconName".into(),
        ValueType::ImageSource => "ImageSource".into(),
        ValueType::EventSet => "readonly EventName[]".into(),
        ValueType::NumberList(_) => "readonly number[]".into(),
        ValueType::Record("<color>") => "Color".into(),
        ValueType::Record("ServiceError") => ts_name("ServiceError").into(),
        ValueType::Record(_) | ValueType::ListOf(..) => "unknown".into(),
        ValueType::Json => "JsonValue".into(),
    }
}

fn shape(out: &mut String, indent: &str, shape: &Shape) {
    match shape {
        Shape::Null => out.push_str("null"),
        Shape::Bool => out.push_str("boolean"),
        Shape::Number | Shape::Integer => out.push_str("number"),
        Shape::Text => out.push_str("string"),
        Shape::Keyword(words) => out.push_str(&keywords(words)),
        Shape::Asset => out.push_str("AssetHandle"),
        Shape::Json => out.push_str("JsonValue"),
        Shape::Nullable(inner) => {
            self::shape(out, indent, inner);
            out.push_str(" | null");
        }
        Shape::List(item) => {
            out.push_str("ReadonlyArray<");
            self::shape(out, indent, item);
            out.push('>');
        }
        Shape::Record(members) => {
            let inner = format!("{indent}  ");
            out.push_str("{\n");
            for member in *members {
                doc(out, &inner, member.summary);
                let _ = write!(out, "{inner}readonly {}: ", member.name);
                self::shape(out, &inner, &member.shape);
                out.push_str(";\n");
            }
            let _ = write!(out, "{indent}}}");
        }
        Shape::OneOf(shapes) => {
            for (index, alternative) in shapes.iter().enumerate() {
                if index > 0 {
                    out.push_str(" | ");
                }
                self::shape(out, indent, alternative);
            }
        }
        Shape::Named(name) => out.push_str(ts_name(name)),
    }
}

/// The TypeScript name of a schema shape. `ServiceError` is the SDK's
/// error class; the wire value it wraps is `ServiceErrorPayload`.
fn ts_name(name: &str) -> &str {
    match name {
        "ServiceError" => "ServiceErrorPayload",
        other => other,
    }
}

fn keywords(words: &[&str]) -> String {
    words
        .iter()
        .map(|word| quote(word))
        .collect::<Vec<_>>()
        .join(" | ")
}

fn quote(text: &str) -> String {
    serde_json::Value::from(text).to_string()
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
        .unwrap_or_default()
}

/// Closes a union started with `export type X =` and `  | …` lines.
fn finish(out: &mut String) {
    if out.ends_with('\n') {
        out.pop();
    }
    out.push_str(";\n");
}

/// A TSDoc comment on one line; `*/` cannot end it early.
fn doc(out: &mut String, indent: &str, text: &str) {
    if text.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}/** {} */", text.replace("*/", "*\\/"));
}
