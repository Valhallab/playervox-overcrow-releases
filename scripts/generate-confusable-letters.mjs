#!/usr/bin/env node
// Generates crates/overcrow-widget-schema/src/confusable_letters.rs from
// Unicode's confusables.txt (UTS #39): every single code point outside ASCII
// whose prototype is one Latin letter or digit of the reserved publisher
// names' or the integrated services' skeletons, so that
// `validate_publisher_name` and the account names read Lisu, Armenian,
// Coptic and other look-alikes as those letters. Blocks of STYLIZED_LETTERS
// are left out: those names are refused before.
//
// Usage: node scripts/generate-confusable-letters.mjs path/to/confusables.txt
// (https://www.unicode.org/Public/security/latest/confusables.txt)
import { readFileSync, writeFileSync } from "node:fs";

const [source] = process.argv.slice(2);
if (!source) {
  console.error("usage: generate-confusable-letters.mjs <confusables.txt>");
  process.exit(2);
}
const text = readFileSync(source, "utf8").replace(/^﻿/, "");
const version = text.match(/^# Version: (\S+)/m)?.[1];
if (!version) throw new Error("no Version line in confusables.txt");

// The letters of playervox, overcrow and valhallab, and of the integrated
// services steam and twitch, the digits and `i` the skeleton folds into
// them.
const TARGETS = new Set([..."abcehilmoprstvwxy0134578"]);
const STYLIZED = [
  [0x0250, 0x02ff],
  [0x13a0, 0x13ff],
  [0x1d00, 0x1dbf],
  [0x2070, 0x209f],
  [0x2100, 0x218f],
  [0x2460, 0x24ff],
  [0xab70, 0xabbf],
  [0x1d400, 0x1d7ff],
  [0x1f100, 0x1f1ff],
];

const pairs = new Map();
for (const raw of text.split("\n")) {
  const line = raw.split("#")[0].trim();
  if (!line) continue;
  const [from, to] = line.split(";").map((field) => field.trim().split(/\s+/));
  if (from.length !== 1 || to.length !== 1) continue;
  const code = Number.parseInt(from[0], 16);
  const target = String.fromCodePoint(Number.parseInt(to[0], 16)).toLowerCase();
  if (code < 0x80 || !TARGETS.has(target)) continue;
  if (STYLIZED.some(([start, end]) => code >= start && code <= end)) continue;
  pairs.set(code, target);
}
const sorted = [...pairs].sort(([a], [b]) => a - b);
const hex = (code) => code.toString(16).toUpperCase().padStart(4, "0");
const body = sorted.map(([code, target]) => `    ('\\u{${hex(code)}}', '${target}'),`).join("\n");
const output = `// Generated by scripts/generate-confusable-letters.mjs from Unicode's
// confusables.txt, version ${version}. Do not edit.
//
// confusables.txt: Copyright © 1991-2026 Unicode, Inc. Distributed under the
// Unicode License v3 (https://www.unicode.org/license.txt).

/// Look-alikes of the letters and digits of the reserved publisher names'
/// and the integrated services' skeletons, from Unicode's confusables (UTS #39, version ${version}),
/// sorted by code point: \`(character, ASCII letter or digit)\`.
pub const UNICODE_CONFUSABLE_LETTERS: &[(char, char)] = &[
${body}
];
`;
writeFileSync(new URL("../crates/overcrow-widget-schema/src/confusable_letters.rs", import.meta.url), output);
console.log(`${sorted.length} look-alikes from confusables.txt ${version}`);
